"""Generate Claude + Codex + Antigravity plugin manifests from a single source of truth.

Each plugin owns one ``plugin.meta.toml``; each harness repo owns one
``harness.toml`` describing the marketplace. From these we render:

- the repo-level Claude ``.claude-plugin/marketplace.json`` (lists all plugins),
- the repo-level Codex ``.agents/plugins/marketplace.json`` (lists every plugin
  that has not opted out with ``codex = false``),
- the repo-level Antigravity ``.agents/plugins.json`` (points Antigravity at
  ``plugins`` with ``exclude`` for any ``antigravity = false`` plugin; omitted
  and pruned when all plugins opt out),
- each plugin's ``.claude-plugin/plugin.json``,
- each plugin's ``.codex-plugin/plugin.json`` (omitted, and pruned, for a
  ``codex = false`` plugin),
- each plugin's ``.antigravity-plugin/plugin.json`` (omitted, and pruned, for an
  ``antigravity = false`` plugin; carries generation metadata under
  ``extensions["harness-kit"]`` because Antigravity's schema sets
  ``additionalProperties: false``),
- each plugin's ``hooks.json`` when ``antigravity_hooks`` is declared (rendered
  from the declared source file, tracked via ``extensions["harness-kit"]["hooksSource"]``,
  and pruned cleanly when removed or opted out — hand-written ``hooks.json`` files
  are never touched),
- each declared plugin-root shared reference, vendored into the citing skill at
  ``skills/<skill>/references/_shared/<name>.md`` (banner + source bytes) so a
  skill folder copied on its own still resolves what it cites.

Claude and Codex per-plugin manifests carry a ``_generated`` marker; Antigravity
per-plugin manifests carry ``extensions["harness-kit"]["generated"]``; the
repo-level manifests are regenerated wholesale (no marker). All generated files
are byte-stable, and a regenerate-and-diff check (``--check``) guarantees they
never drift — including sweeps that prune orphaned vendored code, shared
references, opted-out manifests, and managed Antigravity hooks.

Extracted and generalized from ``smorin-skills`` so the generator is shared,
never copied. The marketplace identity (name/owner/metadata) is parameterized via
``harness.toml`` instead of being hard-coded to one repo.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

_GEN_NOTE = "GENERATED by harness-kit from plugin.meta.toml / harness.toml — do not edit"
_ANTIGRAVITY_SCHEMA = "https://antigravity.google/schemas/v1/plugin.json"


@dataclass(frozen=True)
class PluginMeta:
    name: str
    version: str
    description: str
    author: str = ""
    keywords: list[str] = field(default_factory=list)
    homepage: str = ""
    repository: str = ""
    license: str = ""
    interface: dict = field(default_factory=dict)
    vendor: dict = field(default_factory=dict)
    generated_shared_references: dict = field(default_factory=dict)
    codex: bool = True
    codex_hooks: str | list[str] | None = None
    antigravity: bool = True
    antigravity_hooks: str | None = None
    antigravity_meta: dict = field(default_factory=dict)
    path: Path | None = None


@dataclass(frozen=True)
class MarketplaceMeta:
    name: str
    description: str
    version: str
    owner: dict = field(default_factory=dict)
    vendor_namespace: str = ""
    display_name: str = ""


_META_KEYS = {
    "name",
    "version",
    "description",
    "author",
    "keywords",
    "homepage",
    "repository",
    "license",
    "interface",
    "vendor",
    "generated_shared_references",
    "codex",
    "codex_hooks",
    "antigravity",
    "antigravity_hooks",
}
_GSR_KEYS = {"check_freshness"}
_ANTIGRAVITY_KEYS = {"enabled", "displayName", "logo", "suggestedPrompts", "disabled", "skills"}


def _check_codex_hooks(meta_path: Path, value: object) -> str | list[str]:
    """Codex accepts a ./-prefixed path, or a list of them, inside the plugin root."""
    if isinstance(value, str):
        paths = [value]
    elif isinstance(value, list) and value and all(isinstance(p, str) for p in value):
        paths = [str(p) for p in value]
    else:
        raise ValueError(
            f"{meta_path}: codex_hooks must be a ./-prefixed path or a non-empty list of them"
        )
    for p in paths:
        if not p.startswith("./") or ".." in Path(p).parts:
            raise ValueError(
                f"{meta_path}: codex_hooks path {p!r} must start with ./ and stay inside the plugin"
            )
    return paths[0] if isinstance(value, str) else paths


def _check_antigravity_hooks(meta_path: Path, value: object) -> str:
    """Antigravity accepts a single ./-prefixed relative hook source file inside the plugin root."""
    if not isinstance(value, str):
        raise ValueError(  # noqa: TRY004 - ValueError is this module's uniform contract
            f"{meta_path}: antigravity_hooks must be a ./-prefixed relative path string"
        )
    parts = Path(value).parts
    if not value.startswith("./") or not parts or ".." in parts:
        raise ValueError(
            f"{meta_path}: antigravity_hooks path {value!r} must start with ./ and stay inside the plugin"
        )
    if Path(value) == Path("hooks.json"):
        raise ValueError(
            f"{meta_path}: antigravity_hooks path {value!r} cannot target hooks.json itself"
        )
    return value


def _check_relative_plugin_path(meta_path: Path, field_name: str, value: object) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{meta_path}: [antigravity] {field_name} must be a non-empty string")
    if value.startswith("/") or ".." in Path(value).parts:
        raise ValueError(
            f"{meta_path}: [antigravity] {field_name} path {value!r} must stay inside the plugin"
        )
    return value


def _check_antigravity(meta_path: Path, value: object) -> tuple[bool, dict]:
    """Parse ``antigravity`` as either a boolean opt-in/out or an ``[antigravity]`` table."""
    if isinstance(value, bool):
        return value, {}
    if not isinstance(value, dict):
        raise ValueError(  # noqa: TRY004 - ValueError is this module's uniform contract
            f"{meta_path}: antigravity must be a boolean or table"
        )
    unknown = sorted(set(value) - _ANTIGRAVITY_KEYS)
    if unknown:
        raise ValueError(f"{meta_path}: unknown [antigravity] keys: {unknown}")

    enabled = value.get("enabled", True)
    if not isinstance(enabled, bool):
        raise ValueError(f"{meta_path}: [antigravity] enabled must be a boolean")  # noqa: TRY004

    meta: dict = {}
    if "displayName" in value:
        dn = value["displayName"]
        if not isinstance(dn, str) or not dn.strip():
            raise ValueError(f"{meta_path}: [antigravity] displayName must be a non-empty string")
        meta["displayName"] = dn
    if "logo" in value:
        meta["logo"] = _check_relative_plugin_path(meta_path, "logo", value["logo"])
    if "suggestedPrompts" in value:
        prompts = value["suggestedPrompts"]
        if (
            not isinstance(prompts, list)
            or len(prompts) > 3
            or not all(isinstance(p, str) and p.strip() for p in prompts)
        ):
            raise ValueError(
                f"{meta_path}: [antigravity] suggestedPrompts must be a list of up to 3 non-empty strings"
            )
        meta["suggestedPrompts"] = list(prompts)
    if "disabled" in value:
        if not isinstance(value["disabled"], bool):
            raise ValueError(f"{meta_path}: [antigravity] disabled must be a boolean")
        meta["disabled"] = value["disabled"]
    if "skills" in value:
        raw_skills = value["skills"]
        if isinstance(raw_skills, str):
            meta["skills"] = _check_relative_plugin_path(meta_path, "skills", raw_skills)
        elif isinstance(raw_skills, list) and raw_skills:
            meta["skills"] = [
                _check_relative_plugin_path(meta_path, "skills", s) for s in raw_skills
            ]
        else:
            raise ValueError(
                f"{meta_path}: [antigravity] skills must be a path string or non-empty list of path strings"
            )
    return enabled, meta


def load_meta(meta_path: Path) -> PluginMeta:
    data = tomllib.loads(meta_path.read_text())
    unknown = sorted(set(data) - _META_KEYS)
    if unknown:
        raise ValueError(f"{meta_path}: unknown plugin.meta.toml keys/tables: {unknown}")
    raw_gsr = data.get("generated_shared_references", {})
    if not isinstance(raw_gsr, dict):
        raise ValueError(  # noqa: TRY004 - ValueError is this module's uniform contract
            f"{meta_path}: [generated_shared_references] must be a table"
        )
    gsr = dict(raw_gsr)
    unknown_gsr = sorted(set(gsr) - _GSR_KEYS)
    if unknown_gsr:
        raise ValueError(f"{meta_path}: unknown [generated_shared_references] keys: {unknown_gsr}")
    if "check_freshness" in gsr and not isinstance(gsr["check_freshness"], bool):
        raise ValueError(
            f"{meta_path}: [generated_shared_references] check_freshness must be a boolean"
        )
    for opt_str in ("homepage", "repository", "license"):
        if opt_str in data and not isinstance(data[opt_str], str):
            raise ValueError(f"{meta_path}: {opt_str} must be a string")
    if not isinstance(data.get("codex", True), bool):
        raise ValueError(f"{meta_path}: codex must be a boolean")  # noqa: TRY004
    codex_hooks = (
        _check_codex_hooks(meta_path, data["codex_hooks"]) if "codex_hooks" in data else None
    )
    antigravity, antigravity_meta = (
        _check_antigravity(meta_path, data["antigravity"]) if "antigravity" in data else (True, {})
    )
    antigravity_hooks = (
        _check_antigravity_hooks(meta_path, data["antigravity_hooks"])
        if "antigravity_hooks" in data
        else None
    )
    return PluginMeta(
        name=data["name"],
        version=data["version"],
        description=data["description"],
        author=data.get("author", ""),
        keywords=list(data.get("keywords", [])),
        homepage=data.get("homepage", ""),
        repository=data.get("repository", ""),
        license=data.get("license", ""),
        interface=dict(data.get("interface", {})),
        vendor=dict(data.get("vendor", {})),
        generated_shared_references=gsr,
        codex=data.get("codex", True),
        codex_hooks=codex_hooks,
        antigravity=antigravity,
        antigravity_hooks=antigravity_hooks,
        antigravity_meta=antigravity_meta,
        path=meta_path.parent,
    )


def load_marketplace_meta(root: Path) -> MarketplaceMeta:
    data = tomllib.loads((root / "harness.toml").read_text())
    m = data["marketplace"]
    return MarketplaceMeta(
        name=m["name"],
        description=m["description"],
        version=m["version"],
        owner=dict(m.get("owner", {})),
        vendor_namespace=m.get("vendor_namespace", ""),
        display_name=m.get("display_name", ""),
    )


def render_claude_plugin(m: PluginMeta) -> dict:
    # Claude Code's plugin schema requires author as an object, not a string.
    return {
        "_generated": _GEN_NOTE,
        "name": m.name,
        "version": m.version,
        "description": m.description,
        "author": {"name": m.author} if m.author else {},
        "keywords": m.keywords,
    }


def render_codex_plugin(m: PluginMeta) -> dict:
    interface = {
        "displayName": m.name.replace("-", " ").title(),
        "shortDescription": m.description,
        "longDescription": m.description,
        "category": "Developer Tools",
    }
    interface.update(m.interface)
    out = {
        "_generated": _GEN_NOTE,
        "name": m.name,
        "version": m.version,
        "description": m.description,
        "skills": "./skills/",
        "interface": interface,
    }
    if m.codex_hooks is not None:
        # Codex uses manifest hooks instead of the default hooks/hooks.json,
        # which Claude Code also loads.
        out["hooks"] = m.codex_hooks
    return out


def render_antigravity_plugin(m: PluginMeta) -> dict:
    # Schema: https://antigravity.google/schemas/v1/plugin.json (additionalProperties: false).
    # Generation metadata lives under `extensions["harness-kit"]` so `agy plugin validate --strict`
    # passes with zero warnings.
    display_name = (
        m.antigravity_meta.get("displayName")
        or m.interface.get("displayName")
        or m.name.replace("-", " ").title()
    )
    out: dict = {
        "$schema": _ANTIGRAVITY_SCHEMA,
        "name": m.name,
        "displayName": display_name,
        "version": m.version,
        "description": m.description,
    }
    if "logo" in m.antigravity_meta:
        out["logo"] = m.antigravity_meta["logo"]
    if m.antigravity_meta.get("suggestedPrompts"):
        out["suggestedPrompts"] = m.antigravity_meta["suggestedPrompts"]
    if "skills" in m.antigravity_meta:
        out["skills"] = m.antigravity_meta["skills"]
    if "disabled" in m.antigravity_meta:
        out["disabled"] = m.antigravity_meta["disabled"]
    if m.author:
        out["author"] = {"name": m.author}
    if m.homepage:
        out["homepage"] = m.homepage
    if m.repository:
        out["repository"] = m.repository
    if m.license:
        out["license"] = m.license
    if m.keywords:
        out["keywords"] = m.keywords
    ext_hk: dict = {"generated": _GEN_NOTE}
    if m.antigravity_hooks is not None:
        ext_hk["hooksSource"] = m.antigravity_hooks
    out["extensions"] = {"harness-kit": ext_hk}
    return out


def render_marketplace(metas: list[PluginMeta], mkt: MarketplaceMeta) -> dict:
    return {
        "name": mkt.name,
        "owner": mkt.owner,
        "metadata": {"description": mkt.description, "version": mkt.version},
        "plugins": [
            {
                "name": m.name,
                "source": f"./plugins/{m.name}",
                "description": m.description,
                "version": m.version,
                # Claude Code's marketplace schema requires author as an object, not a string.
                "author": {"name": m.author} if m.author else {},
                "keywords": m.keywords,
            }
            for m in metas
        ],
    }


def render_codex_marketplace(metas: list[PluginMeta], mkt: MarketplaceMeta) -> dict:
    # Schema: https://developers.openai.com/plugins/build/plugins#marketplace-metadata
    return {
        "name": mkt.name,
        "interface": {"displayName": mkt.display_name or mkt.name.replace("-", " ").title()},
        "plugins": [
            {
                "name": m.name,
                "source": {"source": "local", "path": f"./plugins/{m.name}"},
                "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                # Same category as the plugin's own .codex-plugin/plugin.json.
                "category": render_codex_plugin(m)["interface"]["category"],
            }
            for m in metas
            if m.codex
        ],
    }


def render_antigravity_plugins_config(metas: list[PluginMeta]) -> dict | None:
    """Render repo-level ``.agents/plugins.json`` for Antigravity workspace discovery.

    Returns ``None`` when no plugin is enabled for Antigravity, so callers omit
    (and prune) ``.agents/plugins.json``.
    """
    if not any(m.antigravity for m in metas):
        return None
    excluded = [m.path.name if m.path is not None else m.name for m in metas if not m.antigravity]
    entry: dict = {"path": "plugins"}
    if excluded:
        entry["exclude"] = excluded
    return {"entries": [entry]}


def _discover(root: Path) -> list[PluginMeta]:
    return [load_meta(p) for p in sorted((root / "plugins").glob("*/plugin.meta.toml"))]


def _dumps(obj: dict) -> str:
    return json.dumps(obj, indent=2) + "\n"


def _write_if_changed(path: Path, content: str, *, dry_run: bool) -> bool:
    existing = path.read_text() if path.exists() else None
    if existing == content:
        return False
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    return True


_VENDOR_INIT = '"""Vendored copy — generated by harness-kit; do not edit."""\n'


def _vendor_dir(m: PluginMeta, namespace: str) -> Path:
    """The ``_vendor/<namespace>`` dir a ``[vendor]`` plugin owns."""
    assert m.path is not None
    return m.path / "skills" / m.vendor["skill"] / "scripts" / "_vendor" / namespace


def vendor_plugin(root: Path, m: PluginMeta, namespace: str, *, dry_run: bool = False) -> bool:
    """Copy a plugin's runtime package into its skill's ``scripts/_vendor``.

    Only applies to plugins that declare a ``[vendor]`` table (markdown-only
    plugins skip this and return ``False``). ``namespace`` is the Python package
    namespace shared by the repo ``src/<namespace>/`` and the vendored
    ``_vendor/<namespace>/`` so launchers import the same path either way. The
    whole package tree (including subpackages) is mirrored; stale files and empty
    directories are pruned so the vendored copy always matches the source.
    """
    v = m.vendor
    if not v:
        return False
    if not namespace:
        raise ValueError(
            f"plugin {m.name!r} declares [vendor] but harness.toml sets no vendor_namespace"
        )
    package = v["package"]
    src_pkg = root / "src" / namespace / package
    src_files = {p.relative_to(src_pkg) for p in src_pkg.rglob("*.py")}
    if not src_files:
        raise ValueError(
            f"plugin {m.name!r}: vendor source src/{namespace}/{package} is missing or has no .py files"
        )

    vendor_base = _vendor_dir(m, namespace)
    dest_pkg = vendor_base / package
    changed = _write_if_changed(vendor_base / "__init__.py", _VENDOR_INIT, dry_run=dry_run)
    for rel in sorted(src_files):
        changed |= _write_if_changed(dest_pkg / rel, (src_pkg / rel).read_text(), dry_run=dry_run)

    if dest_pkg.is_dir():  # prune stale vendored files, then empty dirs
        for existing in sorted(dest_pkg.rglob("*.py")):
            if existing.relative_to(dest_pkg) not in src_files:
                changed = True
                if not dry_run:
                    existing.unlink()
        if not dry_run:
            for d in sorted(dest_pkg.rglob("*"), reverse=True):
                if d.is_dir() and not any(d.iterdir()):
                    d.rmdir()
    return changed


_SHARED_BLOCK_RE = re.compile(
    r"^```harness-kit-shared-references\n(.*?)^```$", re.MULTILINE | re.DOTALL
)


_SHARED_BANNER_PREFIX = "<!-- GENERATED by harness-kit from "


def _write_bytes_if_changed(path: Path, content: bytes) -> bool:
    if path.is_symlink():
        path.unlink()  # a symlink is never a valid generated copy; never write through it
    elif path.exists() and path.read_bytes() == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)
    return True


def _shared_banner(source_rel: str) -> str:
    return (
        f"{_SHARED_BANNER_PREFIX}{source_rel} — "
        "do not edit; edit that file and run 'harness-kit gen' -->\n\n"
    )


_SHARED_BASENAME_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*\.md")
_SHARED_CITE_RE = re.compile(r"references/_shared/([A-Za-z0-9][A-Za-z0-9._-]*\.md)")


def _declared_shared_refs(m: PluginMeta, skill_md_path: Path, source_names: set[str]) -> list[str]:
    """Parse and validate one SKILL.md's shared-reference declarations.

    The fenced ``harness-kit-shared-references`` block is the only declaration
    position; entries are exact plugin-root basenames, each paired with at least
    one operational ``references/_shared/<name>`` citation, and every such
    citation must be declared — a cited-but-unserviced path is the silent
    breakage this feature exists to prevent.
    """
    where = f"plugin {m.name!r} skill {skill_md_path.parent.name!r}"
    text = skill_md_path.read_text()
    block = _SHARED_BLOCK_RE.search(text)
    entries = (
        [line.strip() for line in block.group(1).splitlines() if line.strip()] if block else []
    )
    seen: set[str] = set()
    for e in entries:
        if not _SHARED_BASENAME_RE.fullmatch(e):
            raise ValueError(f"{where}: shared-reference entry {e!r} is not a plugin-root basename")
        if e in seen:
            raise ValueError(f"{where}: duplicate shared-reference entry {e!r}")
        seen.add(e)
        if e not in source_names:
            by_fold = {n.lower(): n for n in source_names}
            actual = by_fold.get(e.lower())
            if actual is not None:
                raise ValueError(
                    f"{where}: entry {e!r} is an exact-case mismatch with plugin-root reference {actual!r}"
                )
            raise ValueError(
                f"{where}: entry {e!r} matches no plugin-root reference in references/"
            )
    cited = set(_SHARED_CITE_RE.findall(text))
    for c in sorted(cited - seen):
        raise ValueError(
            f"{where}: references/_shared/{c} is cited but not declared in the "
            "harness-kit-shared-references block"
        )
    for e in entries:
        if e not in cited:
            raise ValueError(
                f"{where}: entry {e!r} is declared but never cited as references/_shared/{e}"
            )
    return entries


def vendor_shared_references(
    root: Path,
    m: PluginMeta,
    expected: set[Path] | None = None,
    *,
    dry_run: bool = False,
) -> bool:
    """Copy declared plugin-root references into each citing skill's ``_shared``.

    Each skill's SKILL.md declares plugin-root reference basenames in a fenced
    ``harness-kit-shared-references`` block; every declared name is rendered to
    ``skills/<skill>/references/_shared/<name>`` as ``banner + source bytes`` so
    a skill folder copied on its own still resolves what it cites. Every
    declared destination is added to ``expected``, which keeps it out of the
    orphan sweep — a declared copy is never prunable.
    """
    assert m.path is not None
    root_r = root.resolve()  # the one path known real: every anchor is checked against it
    refs_dir = m.path / "references"
    if refs_dir.is_symlink() or (
        refs_dir.exists() and not refs_dir.resolve().is_relative_to(root_r)
    ):
        raise ValueError(
            f"plugin {m.name!r}: references directory is a symlink or resolves "
            "outside the repository"
        )
    source_names = (
        {p.name for p in refs_dir.iterdir() if p.is_file()} if refs_dir.is_dir() else set()
    )
    check_freshness = m.generated_shared_references.get("check_freshness", True)
    changed = False
    for skill_md_path in sorted(m.path.glob("skills/*/SKILL.md")):
        skill_dir = skill_md_path.parent
        if skill_dir.is_symlink() or not skill_dir.resolve().is_relative_to(root_r):
            raise ValueError(
                f"plugin {m.name!r}: refusing to generate into "
                f"{skill_dir.relative_to(root).as_posix()}: skill directory is a symlink "
                "or resolves outside the repository"
            )
        for name in _declared_shared_refs(m, skill_md_path, source_names):
            src = refs_dir / name
            src_rel = src.relative_to(root).as_posix()
            if src.is_symlink() or not src.resolve().is_relative_to(refs_dir.resolve()):
                raise ValueError(
                    f"plugin {m.name!r}: refusing to vendor {src_rel}: source is a symlink "
                    "or resolves outside the plugin's references directory"
                )
            src_bytes = src.read_bytes()  # bytes end to end: newlines survive verbatim
            if b"../../references/" in src_bytes:
                raise ValueError(
                    f"plugin {m.name!r}: refusing to vendor {src_rel}: source contains "
                    "'../../references/', which escapes a copied skill tree"
                )
            content = _shared_banner(src_rel).encode() + src_bytes
            dest = skill_md_path.parent / "references" / "_shared" / name
            # Parent containment only: a symlinked destination FILE is handled
            # below (check flags it, write replaces it without following it).
            if not dest.parent.resolve().is_relative_to(skill_md_path.parent.resolve()):
                raise ValueError(
                    f"plugin {m.name!r}: refusing to generate "
                    f"{dest.relative_to(root).as_posix()}: a symlinked parent redirects it "
                    "outside the skill directory"
                )
            if expected is not None:
                expected.add(dest)
            if dry_run:
                # The opt-out suppresses only the staleness comparison here; a
                # missing destination fails regardless, and write mode below
                # regenerates unconditionally.
                dest_rel = dest.relative_to(root).as_posix()
                if dest.is_symlink():
                    print(
                        f"harness-kit: symlinked generated reference: {dest_rel}", file=sys.stderr
                    )
                    changed = True
                elif not dest.is_file():
                    print(f"harness-kit: missing generated reference: {dest_rel}", file=sys.stderr)
                    changed = True
                elif check_freshness and dest.read_bytes() != content:
                    print(f"harness-kit: stale generated reference: {dest_rel}", file=sys.stderr)
                    changed = True
            else:
                changed |= _write_bytes_if_changed(dest, content)
    return changed


def _prune_orphan_shared(root: Path, expected: set[Path], *, dry_run: bool) -> bool:
    """Remove banner-owned ``_shared`` copies no current declaration expects.

    Scope is strictly files carrying the generated banner: hand-placed files in
    ``_shared`` are never deleted. Check mode reports without deleting; write
    mode prunes and removes the ``_shared`` dir once empty.
    """
    changed = False
    for f in sorted((root / "plugins").glob("*/skills/*/references/_shared/*")):
        if not f.is_file() or f in expected:
            continue
        # f.parents[2] is the skill dir; never delete through a symlinked
        # references/ or _shared/ that redirects outside the skill tree, and
        # never through a symlinked skill/plugin dir that escapes the repo.
        if not f.resolve().is_relative_to(f.parents[2].resolve()):
            continue
        if not f.resolve().is_relative_to(root.resolve()):
            continue
        with f.open("rb") as fh:  # binary: a stray undecodable file must not crash the sweep
            owned = fh.readline().startswith(_SHARED_BANNER_PREFIX.encode())
        if not owned:
            continue
        changed = True
        if dry_run:
            print(
                f"harness-kit: orphaned generated reference: {f.relative_to(root).as_posix()}",
                file=sys.stderr,
            )
        else:
            f.unlink()
            if not any(f.parent.iterdir()):
                f.parent.rmdir()
    return changed


def _prune_orphan_vendors(root: Path, expected: set[Path], *, dry_run: bool) -> bool:
    """Remove ``_vendor/<ns>`` dirs no current ``[vendor]`` plugin owns.

    Closes the anti-drift hole where dropping a ``[vendor]`` table or renaming a
    skill would otherwise leave stale vendored code that ``--check`` never saw.
    """
    changed = False
    for vd in sorted((root / "plugins").glob("*/skills/*/scripts/_vendor/*")):
        if vd.is_dir() and vd not in expected:
            changed = True
            if not dry_run:
                shutil.rmtree(vd)
    return changed


def _manifest_manages_hooks(manifest_path: Path, plugin_root: Path) -> bool:
    """Return True if an existing ``.antigravity-plugin/plugin.json`` marks ``hooks.json`` as ours."""
    if manifest_path.is_symlink() or not manifest_path.is_file():
        return False
    if not manifest_path.resolve().is_relative_to(plugin_root.resolve()):
        return False
    try:
        doc = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return False
    if not isinstance(doc, dict):
        return False
    ext = doc.get("extensions")
    if not isinstance(ext, dict):
        return False
    hk = ext.get("harness-kit")
    return isinstance(hk, dict) and bool(hk.get("hooksSource"))


def sync_antigravity_hooks(
    root: Path,
    m: PluginMeta,
    *,
    was_managed: bool,
    dry_run: bool = False,
) -> bool:
    """Render or prune ``<plugin-root>/hooks.json`` for Antigravity.

    Antigravity loads hooks strictly from ``<plugin-root>/hooks.json`` and rejects
    unknown top-level keys (so no ``_generated`` marker can live inside ``hooks.json``).
    Instead, ownership is tracked via ``extensions["harness-kit"]["hooksSource"]`` in
    ``.antigravity-plugin/plugin.json``: hand-written ``hooks.json`` files are never
    pruned or clobbered when ``antigravity_hooks`` is unset.
    """
    assert m.path is not None
    dest = m.path / "hooks.json"

    if m.antigravity and m.antigravity_hooks is not None:
        root_r = root.resolve()
        plugin_r = m.path.resolve()
        if m.path.is_symlink() or not plugin_r.is_relative_to(root_r):
            raise ValueError(
                f"plugin {m.name!r}: plugin directory is a symlink or resolves outside the repository"
            )
        cur = m.path
        for part in Path(m.antigravity_hooks).parts:
            cur = cur / part
            if cur.is_symlink():
                raise ValueError(
                    f"plugin {m.name!r}: refusing to read antigravity_hooks source "
                    f"{m.antigravity_hooks!r}: path contains a symlink"
                )
        src = m.path / m.antigravity_hooks
        if not src.exists():
            raise ValueError(
                f"plugin {m.name!r}: antigravity_hooks source {m.antigravity_hooks!r} does not exist"
            )
        if not src.is_file() or not src.resolve().is_relative_to(plugin_r):
            raise ValueError(
                f"plugin {m.name!r}: antigravity_hooks source {m.antigravity_hooks!r} "
                "must be a regular file inside the plugin"
            )
        try:
            hooks_data = json.loads(src.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as e:
            raise ValueError(
                f"plugin {m.name!r}: antigravity_hooks source {m.antigravity_hooks!r} "
                f"is not valid JSON: {e}"
            ) from e
        if not isinstance(hooks_data, dict) or not all(
            isinstance(v, dict) for v in hooks_data.values()
        ):
            raise ValueError(
                f"plugin {m.name!r}: antigravity_hooks source {m.antigravity_hooks!r} "
                "must be a JSON object mapping hook group names to objects"
            )
        for group_name, group in hooks_data.items():
            if "enabled" in group and not isinstance(group["enabled"], bool):
                raise ValueError(
                    f"plugin {m.name!r}: antigravity_hooks group {group_name!r} "
                    "'enabled' must be a boolean"
                )
        content = _dumps(hooks_data).encode()
        dest_rel = dest.relative_to(root).as_posix()
        if dry_run:
            if dest.is_symlink():
                print(f"harness-kit: symlinked generated hooks: {dest_rel}", file=sys.stderr)
                return True
            if not dest.is_file():
                print(f"harness-kit: missing generated hooks: {dest_rel}", file=sys.stderr)
                return True
            if dest.read_bytes() != content:
                print(f"harness-kit: stale generated hooks: {dest_rel}", file=sys.stderr)
                return True
            return False
        return _write_bytes_if_changed(dest, content)

    if was_managed and (dest.is_symlink() or dest.is_file()):
        if dry_run:
            print(
                f"harness-kit: orphaned generated hooks: {dest.relative_to(root).as_posix()}",
                file=sys.stderr,
            )
            return True
        dest.unlink()
        return True

    return False


def write_all(root: Path, *, dry_run: bool = False) -> bool:
    """Render manifests and vendor plugin code. Returns True if anything changed."""
    mkt = load_marketplace_meta(root)
    metas = _discover(root)
    if any(m.vendor for m in metas) and not mkt.vendor_namespace:
        raise ValueError(
            "a plugin declares [vendor] but harness.toml sets no [marketplace].vendor_namespace"
        )

    changed = False
    expected_vendor: set[Path] = set()
    expected_shared: set[Path] = set()
    for m in metas:
        assert m.path is not None
        changed |= _write_if_changed(
            m.path / ".claude-plugin" / "plugin.json",
            _dumps(render_claude_plugin(m)),
            dry_run=dry_run,
        )
        codex_manifest = m.path / ".codex-plugin" / "plugin.json"
        if m.codex:
            changed |= _write_if_changed(
                codex_manifest, _dumps(render_codex_plugin(m)), dry_run=dry_run
            )
        elif codex_manifest.exists():
            changed = True
            if not dry_run:
                codex_manifest.unlink()

        agy_manifest = m.path / ".antigravity-plugin" / "plugin.json"
        was_managed_hooks = _manifest_manages_hooks(agy_manifest, m.path)
        changed |= sync_antigravity_hooks(root, m, was_managed=was_managed_hooks, dry_run=dry_run)
        if m.antigravity:
            changed |= _write_if_changed(
                agy_manifest, _dumps(render_antigravity_plugin(m)), dry_run=dry_run
            )
        elif not agy_manifest.parent.is_symlink() and (
            agy_manifest.exists() or agy_manifest.is_symlink()
        ):
            changed = True
            if not dry_run:
                agy_manifest.unlink()
                if agy_manifest.parent.is_dir() and not any(agy_manifest.parent.iterdir()):
                    agy_manifest.parent.rmdir()

        changed |= vendor_plugin(root, m, mkt.vendor_namespace, dry_run=dry_run)
        changed |= vendor_shared_references(root, m, expected_shared, dry_run=dry_run)
        if m.vendor:
            expected_vendor.add(_vendor_dir(m, mkt.vendor_namespace))

    changed |= _prune_orphan_vendors(root, expected_vendor, dry_run=dry_run)
    changed |= _prune_orphan_shared(root, expected_shared, dry_run=dry_run)
    changed |= _write_if_changed(
        root / ".claude-plugin" / "marketplace.json",
        _dumps(render_marketplace(metas, mkt)),
        dry_run=dry_run,
    )
    changed |= _write_if_changed(
        root / ".agents" / "plugins" / "marketplace.json",
        _dumps(render_codex_marketplace(metas, mkt)),
        dry_run=dry_run,
    )
    agy_plugins_cfg = root / ".agents" / "plugins.json"
    agy_plugins_doc = render_antigravity_plugins_config(metas)
    if agy_plugins_doc is not None:
        changed |= _write_if_changed(agy_plugins_cfg, _dumps(agy_plugins_doc), dry_run=dry_run)
    elif agy_plugins_cfg.exists() or agy_plugins_cfg.is_symlink():
        changed = True
        if not dry_run:
            agy_plugins_cfg.unlink()
    return changed
